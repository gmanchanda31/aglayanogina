/**
 * Per-entry content audit.
 *
 * For every section + slug:
 *   - Title from old (parsed.json listing) vs Sanity
 *   - Plain-text description from old vs Sanity (PortableText flattened)
 *   - Image count from old vs Sanity
 *   - Missing entries (in old but not in new, or vice versa)
 *
 * Writes AUDIT-FULL.md.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@sanity/client";

const TOKEN = process.env.SANITY_WRITE_TOKEN;
if (!TOKEN) throw new Error("SANITY_WRITE_TOKEN missing");

const c = createClient({
  projectId: "w6axlzhx",
  dataset: "production",
  apiVersion: "2025-01-01",
  token: TOKEN,
  useCdn: false,
});

const parsed = JSON.parse(readFileSync("./data/parsed.json", "utf8"));
const plan = JSON.parse(readFileSync("./data/image_plan.json", "utf8"));
const ZWJ = /‍/g;
const norm = (s) => (s ?? "").replace(ZWJ, "").replace(/\s+/g, " ").trim();

function getPage(file) {
  return parsed.find((p) => p.file === file);
}

function paragraphsOf(file) {
  const page = getPage(file);
  if (!page) return [];
  return page.blocks
    .filter(([k]) => k === "p" || k === "blockquote")
    .map(([, v]) => norm(typeof v === "string" ? v : ""))
    .filter(Boolean);
}

function imageCountOf(section, slug) {
  return (plan[`${section}/${slug}`] ?? []).length;
}

/** Plain-text from a Sanity Portable Text body. */
function ptToParagraphs(body) {
  if (!Array.isArray(body)) return [];
  return body
    .map((node) => {
      if (node._type === "block") {
        return (node.children ?? []).map((c) => c.text).join("");
      }
      if (node._type === "pullQuote") return node.text ?? "";
      return "";
    })
    .map(norm)
    .filter(Boolean);
}

/** Flatten an entry doc's content + metadata into a single comparable string. */
function flattenSanityEntry(doc) {
  const parts = [doc.title];
  if (doc.medium) parts.push(doc.medium);
  if (doc.year) parts.push(doc.year);
  if (doc.location) parts.push(doc.location);
  if (doc.dimensions) parts.push(doc.dimensions);
  if (doc.venue) parts.push(doc.venue);
  if (doc.city) parts.push(doc.city);
  if (doc.curator) parts.push(doc.curator);
  parts.push(...ptToParagraphs(doc.description ?? doc.body ?? []));
  return parts.map(norm).filter(Boolean);
}

const lines = [];
lines.push("# Full content audit\n");
lines.push("Comparing every entry on the live site (Sanity) against the\n");
lines.push("old site (parsed.json + image_plan.json). Generated by\n");
lines.push("`scripts/full-content-audit.mjs`.\n\n---\n");

const SECTIONS = [
  { section: "projects", sanityType: "project" },
  { section: "exhibitions", sanityType: "exhibition" },
  { section: "illustrations", sanityType: "illustration" },
  { section: "photographs", sanityType: "photographSet" },
  { section: "writings", sanityType: "writing" },
];

let totalDiscrepancies = 0;

for (const { section, sanityType } of SECTIONS) {
  lines.push(`## ${section}\n`);

  // Old listing
  const indexPage = getPage(`_raw/${section}.html`);
  const oldEntries = (indexPage?.listing ?? [])
    .filter((it) => it.href && it.title && !it.href.includes("webflow-io"))
    .map((it) => {
      const rawSlug = it.href.replace(/^\/[^/]+\//, "");
      return { rawSlug, routeSlug: rawSlug.replace(/-+$/, ""), title: norm(it.title) };
    });

  // New (Sanity)
  const newDocs = await c.fetch(
    `*[_type == $type] { _id, title, "slug": slug.current, year, medium, location, dimensions, venue, city, curator, description, body,
      "imageCount": coalesce(count(images), 0) + coalesce(count(gallery), 0) + select(defined(hero) => 1, 0)
    }`,
    { type: sanityType },
  );

  const newBySlug = new Map();
  for (const d of newDocs) {
    const route = (d.slug ?? "").replace(/-+$/, "");
    newBySlug.set(route, d);
  }

  // Missing from new
  const missing = oldEntries.filter((e) => !newBySlug.has(e.routeSlug));
  if (missing.length > 0) {
    totalDiscrepancies += missing.length;
    lines.push(`**Missing from new site (${missing.length}):**\n`);
    for (const m of missing) {
      lines.push(`- ${m.title} (\`${m.rawSlug}\`)`);
    }
    lines.push("");
  }

  // Extra in new
  const oldRoutes = new Set(oldEntries.map((e) => e.routeSlug));
  const extras = [...newBySlug.entries()].filter(([k]) => !oldRoutes.has(k));
  if (extras.length > 0) {
    totalDiscrepancies += extras.length;
    lines.push(`**Extra on new site (${extras.length}):**\n`);
    for (const [slug, doc] of extras) {
      lines.push(`- ${doc.title} (\`${slug}\`)`);
    }
    lines.push("");
  }

  // Per-entry comparison
  for (const old of oldEntries) {
    const doc = newBySlug.get(old.routeSlug);
    if (!doc) continue;

    const issues = [];

    // Title check
    if (norm(doc.title) !== norm(old.title)) {
      issues.push(`title differs: old "${old.title}" vs new "${doc.title}"`);
    }

    // Image count check
    const oldImageCount = imageCountOf(section, old.rawSlug);
    const newImageCount = doc.imageCount ?? 0;
    if (section !== "writings" && oldImageCount !== newImageCount) {
      issues.push(`image count: old ${oldImageCount} vs new ${newImageCount}`);
    }

    // Body fidelity — only for entries with text bodies
    const oldParas = paragraphsOf(`_raw/${section}/${old.rawSlug}.html`).filter(
      (p) => p !== old.title,
    );
    const newParas = ptToParagraphs(doc.description ?? doc.body ?? []);

    // Compare each old paragraph: present anywhere in new content?
    const newHaystack = newParas.map(norm);
    const flatHaystack = new Set([
      ...newHaystack,
      // Also accept metadata fields (medium / year / etc) since those moved
      // out of paragraphs into structured fields
      doc.medium,
      doc.year,
      doc.location,
      doc.dimensions,
      doc.venue,
      doc.city,
      doc.curator,
      ...flattenSanityEntry(doc),
    ].filter(Boolean).map(norm));

    const missingParas = oldParas.filter((p) => {
      // Skip very short metadata-shaped lines
      if (p.length < 20) return false;
      // Allow fuzzy match: any new paragraph that contains the old text
      return ![...flatHaystack].some(
        (np) => np.includes(p) || p.includes(np) || jaccard(p, np) > 0.8,
      );
    });

    if (missingParas.length > 0) {
      issues.push(
        `${missingParas.length} paragraph(s) missing/changed on new site:`,
      );
      for (const p of missingParas) {
        issues.push(`    - ${p.slice(0, 140)}${p.length > 140 ? "…" : ""}`);
      }
    }

    if (issues.length > 0) {
      totalDiscrepancies += 1;
      lines.push(`### ✗ ${old.title} (\`/${section}/${old.routeSlug}\`)\n`);
      for (const i of issues) lines.push(`- ${i}`);
      lines.push("");
    }
  }

  lines.push(`*${oldEntries.length} entries checked.*\n`);
}

function jaccard(a, b) {
  const wordsA = new Set(a.toLowerCase().split(/\s+/));
  const wordsB = new Set(b.toLowerCase().split(/\s+/));
  let inter = 0;
  for (const w of wordsA) if (wordsB.has(w)) inter++;
  return inter / (wordsA.size + wordsB.size - inter);
}

lines.push("---\n");
lines.push(`**Total discrepancies: ${totalDiscrepancies}**\n`);

writeFileSync("./AUDIT-FULL.md", lines.join("\n"));
console.log(`Wrote AUDIT-FULL.md (${totalDiscrepancies} discrepancies)`);
